#!/usr/bin/env python3
"""Read-only, CPU-only paired split A/B readout-stability analysis.
Inputs are JSONL outputs generated by 351_self_jlens_validation.py --mode generic/paper
with --lens lens_A.pt or lens_B.pt and separate --out folders.
"""
import argparse,csv,hashlib,json,math,random,statistics
from pathlib import Path
LAYERS=[24,32,40,48,56,62]
METRICS=['kl_final_to_lens_nats','top1_agree','top10_overlap','final_top1_rank','final_top1_reciprocal_rank']
def sha(p):
 h=hashlib.sha256()
 with open(p,'rb') as f:
  for block in iter(lambda:f.read(1048576),b''):h.update(block)
 return h.hexdigest()
def read(p,task):
 if not p.is_file():raise RuntimeError(f'Missing input {p}')
 rows={}
 for line in p.read_text(encoding='utf8').splitlines():
  if not line.strip():continue
  x=json.loads(line);k=str(x['id'])
  if k in rows:raise RuntimeError(f'Duplicate {task} ID {k}: {p}')
  rows[k]=x
 return rows
def percentile(v,p):
 q=(len(v)-1)*p; lo=math.floor(q);hi=math.ceil(q)
 return v[lo]*(hi-q)+v[hi]*(q-lo) if hi!=lo else v[lo]
def ci_boot(a,b,seed=20261018,nboot=2000):
 assert len(a)==len(b) and len(a)>0
 differences=[x-y for x,y in zip(a,b)]
 rng=random.Random(seed);n=len(a);outs=[]
 for _ in range(nboot):outs.append(sum(differences[rng.randrange(n)] for _ in range(n))/n)
 outs.sort()
 return statistics.mean(differences),percentile(outs,.025),percentile(outs,.975)
def main():
 ap=argparse.ArgumentParser()
 ap.add_argument('--root',type=Path,required=True,help='Split-half experiment root')
 ap.add_argument('--n',type=int,default=20)
 args=ap.parse_args();root=args.root
 for half in 'AB':
  p=root/'fits'/f'complete_{half}.json'
  if not p.exists():raise RuntimeError(f'{half} fit not finished: missing {p}')
  data=json.loads(p.read_text())
  if data.get('n_prompts')!=50:raise RuntimeError(f'{half} fit count != 50')
  if not (root/'fits'/f'lens_{half}.pt').is_file():raise RuntimeError(f'{half} lens missing')
 ca=json.loads((root/'fits'/'complete_A.json').read_text())['config'];cb=json.loads((root/'fits'/'complete_B.json').read_text())['config']
 if set(ca['indices'])&set(cb['indices']) or set(ca['indices'])|set(cb['indices'])!=set(range(100)):raise RuntimeError('Halves not independent/complementary')
 for k in ('model','model_revision','corpus_sha256','source_layers','target_layer','dim_batch','max_seq_len','skip_first','dtype'):
  if ca[k]!=cb[k]:raise RuntimeError(f'A/B fit protocol mismatch: {k}')
 raw=root/'readout';out=root/'readout_comparison'
 for sub in ('summary','figures','reports','config'):(out/sub).mkdir(parents=True,exist_ok=True)
 rows=[]; detail=[]
 for task in ('generic','paper'):
  A=read(raw/'A'/'raw'/f'{task}.jsonl',task)
  B=read(raw/'B'/'raw'/f'{task}.jsonl',task)
  if len(A)!=args.n or len(B)!=args.n or set(A)!=set(B):raise RuntimeError(f'{task}: unmatched IDs; A={len(A)} B={len(B)}')
  ids=sorted(A)
  for k in ids:
   a=A[k];b=B[k]
   if a['prompt']!=b['prompt'] or a['token_count']!=b['token_count']:raise RuntimeError(f'{task} prompt/token mismatch: {k}')
   if a['config']['revision']!=b['config']['revision']:raise RuntimeError(f'{task} revision mismatch: {k}')
  for l in LAYERS:
   for m in METRICS:
    va=[float(A[k]['metrics'][str(l)]['jlens'][m]) for k in ids]
    vb=[float(B[k]['metrics'][str(l)]['jlens'][m]) for k in ids]
    if not all(math.isfinite(x) for x in va+vb):raise RuntimeError('Nonfinite readout metric')
    d,low,high=ci_boot(va,vb,seed=20261018+l+len(task)+sum(map(ord,m)))
    rows.append({'task':task,'layer':l,'metric':m,'n_paired':len(ids),'mean_A':statistics.mean(va),'mean_B':statistics.mean(vb),'mean_delta_A_minus_B':d,'ci95_low':low,'ci95_high':high})
    for i,k in enumerate(ids):detail.append({'task':task,'id':k,'layer':l,'metric':m,'A':va[i],'B':vb[i],'delta_A_minus_B':va[i]-vb[i]})
  print(task,'paired',len(ids),'prompts')
 for fn,rr in (('paired_summary.csv',rows),('paired_per_prompt.csv',detail)):
  with (out/'summary'/fn).open('w',newline='') as f:
   writer=csv.DictWriter(f,fieldnames=list(rr[0]));writer.writeheader();writer.writerows(rr)
 import matplotlib;matplotlib.use('Agg')
 import matplotlib.pyplot as plt
 for task in ('generic','paper'):
  for metric,title in [('kl_final_to_lens_nats','KL(final || readout) — lower is better'),('final_top1_reciprocal_rank','Final top-1 token MRR — higher is better'),('top10_overlap','Top-10 overlap — higher is better')]:
   s=sorted((r for r in rows if r['task']==task and r['metric']==metric),key=lambda r:r['layer'])
   fig,ax=plt.subplots(figsize=(8,4.8));x=[r['layer'] for r in s]
   ax.plot(x,[r['mean_A'] for r in s],marker='o',linestyle='-',label='Split A (50)')
   ax.plot(x,[r['mean_B'] for r in s],marker='s',linestyle='--',label='Split B (50)')
   ax.set(xticks=x,xlabel='Source layer',ylabel=metric,title=f'{task.title()} split-half stability: {title}');ax.legend();ax.grid(alpha=.25)
   fig.tight_layout()
   for ext in ('png','pdf'):fig.savefig(out/'figures'/f'{task}_{metric}.{ext}',dpi=180)
   plt.close(fig)
 lines=['# Self-fitted J-Lens — Split-half held-out readout stability','',
        'Both independently fitted 50-prompt lenses were evaluated on exact paired prompts using the original 351_self_jlens_validation.py scoring protocol.',
        '', 'Important: A/B differences are descriptive, not a test that either lens improves over Neuronpedia. The 95% percentile bootstrap intervals are unadjusted for multiple layers/metrics. The fit/eval dataset-independence audit remains separate.',
        '', '| Distribution | Layer | KL A | KL B | Delta A-B [95% CI] | MRR A | MRR B |','|---|---:|---:|---:|---|---:|---:|']
 for task in ('generic','paper'):
  for l in LAYERS:
   get=lambda m:next(r for r in rows if r['task']==task and r['layer']==l and r['metric']==m)
   k=get('kl_final_to_lens_nats');m=get('final_top1_reciprocal_rank')
   lines.append(f"| {task} | {l} | {k['mean_A']:.4f} | {k['mean_B']:.4f} | {k['mean_delta_A_minus_B']:+.4f} [{k['ci95_low']:+.4f}, {k['ci95_high']:+.4f}] | {m['mean_A']:.6f} | {m['mean_B']:.6f} |")
 lines+=['','## Provenance','',f"- Lens A SHA256: {sha(root/'fits'/'lens_A.pt')}",f"- Lens B SHA256: {sha(root/'fits'/'lens_B.pt')}",f"- Model revision: {ca['model_revision']}",f"- Corpus SHA256: {ca['corpus_sha256']}",'- n=20 independently scored prompts for each distribution; 6 common source layers.','- Missing or mismatched examples cause hard failure; no silent dropping.']
 (out/'reports'/'readout_stability_report.md').write_text('\n'.join(lines)+'\n',encoding='utf8')
 (out/'config'/'run_config.json').write_text(json.dumps({'protocol':'351_split_readout_compare_v1','n_paired_per_task':args.n,'n_bootstrap':2000,'seed_base':20261018,'lens_A_sha256':sha(root/'fits'/'lens_A.pt'),'lens_B_sha256':sha(root/'fits'/'lens_B.pt'),'fit_A':ca,'fit_B':cb},indent=2)+'\n')
 print('COMPLETE:',out)
if __name__=='__main__':main()
